#!/usr/bin/env python3
"""Writes the golden frames the firmware tests decode: real frames from the
fake controllers, so the C parser is checked against a second, independent
MAVLink implementation (pymavlink) and the ICD schema.

    tools/sim/make_golden.py > firmware/sync-mcu/tests/controller_link/src/golden.h
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from arcsim import scenario  # noqa: E402
from arcsim.dialect import load_dialect  # noqa: E402
from arcsim.fleet import build  # noqa: E402
from arcsim.transport import MemoryTransport  # noqa: E402


def c_array(name, data):
    body = ",".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};\n"


def main():
    dialect, version = load_dialect()
    links = {n: MemoryTransport() for n in ("FL", "RL")}
    events = scenario.load_scenario({"events": [
        {"t_ms": 0, "corner": "FL", "action": "speed", "mps": 3.0},
        {"t_ms": 200, "corner": "RL", "action": "state", "bits": ["ESTOP"]},
        {"t_ms": 250, "corner": "RL", "action": "state", "bits": []},
        {"t_ms": 250, "corner": "RL", "action": "fault", "code": 7},
    ]})
    fleet = build(links, seed=1, events=events)
    fleet.run(300_000_000)

    parser = dialect.MAVLink(None)
    parser.robust_parsing = True

    def frames(name):
        out = []
        for _, data in links[name].writes:
            out.append((parser.parse_buffer(data)[0], data))
        return out

    fl = [(m, d) for m, d in frames("FL") if m.get_type() == "ARC_MOTOR_STATUS"]
    link = [(m, d) for m, d in frames("FL") if m.get_type() == "ARC_LINK_STATUS"][0]
    rl = [(m, d) for m, d in frames("RL") if m.get_type() == "ARC_MOTOR_STATUS"]
    last = fl[-3:]
    estop = next((m, d) for m, d in rl if m.state == 1 and m.fault == 0)
    fault = next((m, d) for m, d in rl if m.fault == 7 and m.state == 0)

    out = ["/* Generated by tools/sim/make_golden.py from the fake controllers: do not edit. */\n",
           "#include <stdint.h>\n\n"]
    out.append(c_array("golden_fl_status", b"".join(d for _, d in last)))
    out.append(f"#define GOLDEN_FL_STATUS_FRAMES {len(last)}\n")
    out.append(f"#define GOLDEN_FL_FIRST_ERPM {last[0][0].erpm}\n")
    out.append(f"#define GOLDEN_FL_FIRST_TIME_NS {last[0][0].time_ns}ULL\n")
    out.append(f"#define GOLDEN_FL_FIRST_SEQ {last[0][0].get_header().seq}\n")
    out.append(c_array("golden_fl_link_status", link[1]))
    out.append(f"#define GOLDEN_LINK_VERSION {link[0].protocol_version}\n")
    out.append(c_array("golden_rl_estop", estop[1]))
    out.append(c_array("golden_rl_fault", fault[1]))
    out.append(f"#define GOLDEN_RL_FAULT_CODE {fault[0].fault}\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
